const hoursAgo = (h: number) =>
  new Date(Date.now() - h * 60 * 60 * 1000).toISOString();

const daysAgo = (d: number, hour = 14) => {
  const dt = new Date();
  dt.setDate(dt.getDate() - d);
  dt.setHours(hour, 15, 0, 0);
  return dt.toISOString();
};

const daysFromNow = (d: number) => {
  const dt = new Date();
  dt.setDate(dt.getDate() + d);
  return dt.toISOString();
};

